  /* ---- Contraste dos alertas (valores calculados) ---- */
  function lum(h) { var c = [1, 3, 5].map(function (i) { var v = parseInt(h.substr(i, 2), 16) / 255; return v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4); }); return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]; }
  function ratio(a, b) { var x = lum(a), y = lum(b), hi = Math.max(x, y), lo = Math.min(x, y); return (hi + 0.05) / (lo + 0.05); }
  function paintContrast() {
    var ct = $('#contrast'); if (!ct) return;
    var P = [['#00B374', L('Level 1', 'Nível 1')], ['#FF9500', L('Level 2', 'Nível 2')], ['#E63946', L('Level 3', 'Nível 3')]];
    ct.innerHTML = P.map(function (p) {
      var rb = ratio(p[0], '#000000'), rc = ratio(p[0], '#111317');
      var bd = function (r) { return r >= 7 ? 'AAA' : r >= 4.5 ? 'AA' : r >= 3 ? 'AA large' : 'fail'; };
      return '<div class="cp"><i style="background:' + p[0] + ';color:#000">Aa</i><b>' + rb.toFixed(1) + ':1</b><span>' + p[1] + ' · ' + L('black text on the color', 'texto preto sobre a cor') + '</span><em>' + bd(rb) + '</em><span>' + rc.toFixed(1) + ':1 ' + L('color on the card background', 'cor sobre o fundo do card') + '</span></div>';
    }).join('');
  }

